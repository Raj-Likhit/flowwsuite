import { useCallback } from 'react';
import jsPDF from 'jspdf';
import { useAppStore } from '../../store/useAppStore';

export const useAttendanceReport = () => {
    const { attendance } = useAppStore();

    const generateReport = useCallback(() => {
        const { totalClasses, attendedClasses } = attendance;
        const percentage = totalClasses > 0
            ? Math.round((attendedClasses / totalClasses) * 100)
            : 0;
        const isAbove75 = percentage >= 75;
        const safeToSkip = Math.max(0, Math.floor(attendedClasses / 0.75) - totalClasses);
        const classesNeeded = Math.max(0, Math.ceil((0.75 * totalClasses - attendedClasses) / 0.25));

        const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
        const pageWidth = doc.internal.pageSize.getWidth();
        const centerX = pageWidth / 2;

        // Background
        doc.setFillColor(10, 10, 10);
        doc.rect(0, 0, pageWidth, 297, 'F');

        // Header bar
        doc.setFillColor(99, 102, 241);
        doc.rect(0, 0, pageWidth, 40, 'F');

        // Title
        doc.setTextColor(255, 255, 255);
        doc.setFontSize(22);
        doc.setFont('helvetica', 'bold');
        doc.text('FlowSuite', centerX, 18, { align: 'center' });
        doc.setFontSize(10);
        doc.setFont('helvetica', 'normal');
        doc.text('Attendance Report', centerX, 28, { align: 'center' });

        // Date
        doc.setFontSize(9);
        doc.setTextColor(200, 200, 200);
        doc.text(`Generated: ${new Date().toLocaleDateString('en-IN', {
            weekday: 'long', year: 'numeric', month: 'long', day: 'numeric'
        })}`, centerX, 55, { align: 'center' });

        // Big percentage
        doc.setFontSize(64);
        doc.setFont('helvetica', 'bold');
        if (percentage > 80) {
            doc.setTextColor(16, 185, 129); // emerald
        } else if (percentage >= 75) {
            doc.setTextColor(245, 158, 11); // amber
        } else {
            doc.setTextColor(239, 68, 68); // crimson
        }
        doc.text(`${percentage}%`, centerX, 90, { align: 'center' });

        // Stats row
        doc.setFontSize(11);
        doc.setTextColor(255, 255, 255);
        const statsY = 110;

        doc.setFont('helvetica', 'bold');
        doc.text('Total Classes', centerX - 35, statsY, { align: 'center' });
        doc.text('Attended', centerX + 35, statsY, { align: 'center' });

        doc.setFontSize(24);
        doc.text(`${totalClasses}`, centerX - 35, statsY + 12, { align: 'center' });
        doc.text(`${attendedClasses}`, centerX + 35, statsY + 12, { align: 'center' });

        // Divider
        doc.setDrawColor(50, 50, 50);
        doc.setLineWidth(0.3);
        doc.line(30, 135, pageWidth - 30, 135);

        // Status card
        doc.setFontSize(12);
        doc.setFont('helvetica', 'bold');
        const statusY = 150;

        if (isAbove75) {
            doc.setTextColor(16, 185, 129);
            doc.text('Status: Safe Zone', centerX, statusY, { align: 'center' });
            doc.setFontSize(10);
            doc.setTextColor(180, 180, 180);
            doc.setFont('helvetica', 'normal');
            doc.text(`You can safely skip ${safeToSkip} more ${safeToSkip === 1 ? 'class' : 'classes'}.`, centerX, statusY + 10, { align: 'center' });
        } else {
            doc.setTextColor(239, 68, 68);
            doc.text('Status: Recovery Mode', centerX, statusY, { align: 'center' });
            doc.setFontSize(10);
            doc.setTextColor(180, 180, 180);
            doc.setFont('helvetica', 'normal');
            doc.text(`You need ${classesNeeded} consecutive ${classesNeeded === 1 ? 'class' : 'classes'} to reach 75%.`, centerX, statusY + 10, { align: 'center' });
        }

        // Footer
        doc.setFontSize(8);
        doc.setTextColor(100, 100, 100);
        doc.text('Generated by FlowSuite — flowsuite.app', centerX, 280, { align: 'center' });

        // Save
        doc.save(`FlowSuite_Attendance_${new Date().toISOString().slice(0, 10)}.pdf`);
    }, [attendance]);

    return { generateReport };
};
